"""
Regression tests for srs_tax_regime.py (Model 3). Expected values were generated by running
`python srs_tax_regime.py` against the real historical data in
data/tax_brackets_historical.json (Data.gov.sg / IRAS, see that file for citation) and checked
by hand against docs/findings.md #7's closed-form crossover. If a change breaks one of these,
the change is wrong or the finding needs re-deriving — do not just update the number.

Run with:  python -m pytest tests/        (or, without pytest)  python tests/test_srs_tax_regime.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import srs_model as m  # noqa: E402
import srs_tax_regime as tr  # noqa: E402


def close(a, b, tol):
    return abs(a - b) <= tol


# ------------------------------------------------------------------- historical data integrity
def test_six_real_schedules_loaded():
    assert [h["ya"] for h in tr.HISTORY] == [2003, 2006, 2007, 2012, 2017, 2024]


def test_ya2024_matches_current_live_brackets():
    # the historical file's 2024 entry must be identical to data/tax_brackets_ya2026.json,
    # since IRAS states YA2024 rates are "unchanged for YA2026"
    ya2024 = next(h for h in tr.HISTORY if h["ya"] == 2024)
    assert ya2024["brackets"] == m.BRACKETS


def test_thresholds_up_to_80k_never_moved():
    for h in tr.HISTORY:
        uppers = [u for u, _ in h["brackets"][:4]]
        assert uppers == [20_000.0, 30_000.0, 40_000.0, 80_000.0]


def test_top_rate_rose_from_20_to_24_percent_2007_to_2024():
    by_ya = {h["ya"]: h["brackets"][-1][1] for h in tr.HISTORY}
    assert close(by_ya[2007], 0.20, 1e-9)
    assert close(by_ya[2024], 0.24, 1e-9)


# --------------------------------------------------------------------------- calibration facts
def test_calibration_facts():
    f = tr.calibration_facts()
    assert f["revision_yas"] == [2012, 2017, 2024]
    assert close(f["avg_interval_years"], 17 / 3, 1e-9)
    assert close(f["avg_step_per_revision"], 0.04 / 3, 1e-9)       # 0 + 2pp + 2pp over 3 revisions
    assert close(f["smooth_drift_per_year"], 0.04 / 17, 1e-9)      # 4pp over 17 years, endpoint to endpoint
    assert f["thresholds_frozen_since_ya"] == 2003


def test_discrete_and_smooth_drift_agree_on_50y_total():
    # calibrated so both scenarios reach (almost) the same cumulative drift by year 50 and
    # differ only in lumpy vs. continuous arrival
    f = tr.calibration_facts()
    n_revisions_by_50 = 1 + 50 // f["avg_interval_years"]  # revisions that have landed by year 50
    discrete_total = n_revisions_by_50 * f["avg_step_per_revision"]
    smooth_total = f["smooth_drift_per_year"] * 50
    assert close(discrete_total, smooth_total, 0.02)  # within 2pp over 50 years


# ----------------------------------------------------------------- real historical frontier
def test_historical_frontier_matches_findings_closed_form():
    # docs/findings.md #7: tc=7% crossover is $1,853,216 under the brackets that have held
    # since YA2012 (120,000-edge band first exceeding 14%)
    rows = tr.historical_frontier()
    by_ya_tc = {(r["year_of_assessment"], r["relief_rate"]): r["crossover_pot"] for r in rows}
    assert close(by_ya_tc[(2012, 0.07)], 1_853_216, 1)
    assert close(by_ya_tc[(2017, 0.07)], 1_853_216, 1)
    assert close(by_ya_tc[(2024, 0.07)], 1_853_216, 1)
    # docs/findings.md #7: tc=11.5% only gets a crossover once the top rate exceeds 23%, i.e.
    # only from the YA2024 reform onward (24% top rate) — never before
    assert by_ya_tc[(2007, 0.115)] is None
    assert by_ya_tc[(2012, 0.115)] is None
    assert by_ya_tc[(2017, 0.115)] is None
    assert close(by_ya_tc[(2024, 0.115)], 15_443_470, 1)


def test_tc_seven_percent_doubled_from_2003_to_2007():
    # the pre-2012 restructuring: in YA2003-2006 the first band to exceed 14% was the 320k
    # edge (1,235,478); the 2007 cut pushed the >14% threshold up to the (then) top band,
    # pushing the crossover to 2,470,955 before the 2012 reform introduced the 120k band
    rows = tr.historical_frontier()
    by_ya_tc = {(r["year_of_assessment"], r["relief_rate"]): r["crossover_pot"] for r in rows}
    assert close(by_ya_tc[(2003, 0.07)], 1_235_478, 1)
    assert close(by_ya_tc[(2007, 0.07)], 2_470_955, 1)


# --------------------------------------------------------------------- 50-year projections
def test_projection_year_zero_matches_today():
    rows = tr.projected_frontier(relief_rates=(0.115,), checkpoints=(0,))
    assert close(rows[0]["crossover_discrete"], 15_443_470, 1)
    assert close(rows[0]["crossover_smooth"], 15_443_470, 1)


def test_projection_crossover_falls_as_regime_drifts_up():
    # a rising tax regime makes the breakeven-exit-rate threshold easier to clear at a smaller
    # pot, so the crossover pot size should be non-increasing over the 50-year horizon
    rows = tr.projected_frontier(relief_rates=(0.115,), checkpoints=(0, 10, 20, 30, 40, 50))
    discrete_vals = [r["crossover_discrete"] for r in rows]
    smooth_vals = [r["crossover_smooth"] for r in rows]
    assert all(a >= b for a, b in zip(discrete_vals, discrete_vals[1:]))
    assert all(a >= b for a, b in zip(smooth_vals, smooth_vals[1:]))


def test_zero_years_projection_is_a_no_op():
    discrete = tr.project_discrete(years=0)
    smooth = tr.project_smooth(years=0)
    assert discrete[0] == tuple(m.BRACKETS) or discrete[0] == list(m.BRACKETS)
    assert smooth[0] == discrete[0]


