"""
Turns the raw numbers from srs_simulation.py into a plain-language Markdown report.
Kept separate from srs_simulation.py so the simulation engine has no formatting concerns.
The report mirrors the dashboard's order: bottom line first, then the pieces behind it.
"""


def _money(x):
    return f"${x:,.0f}"


def _friendly(x):
    """Child-readable magnitude: $1.5M, $150k, $950."""
    ax = abs(x)
    sign = "-" if x < 0 else ""
    if ax >= 1_000_000:
        return f"{sign}${ax / 1_000_000:.2f}M"
    if ax >= 1_000:
        return f"{sign}${ax / 1_000:.0f}k"
    return f"{sign}${ax:,.0f}"


def _pct(x):
    return f"{x * 100:.1f}%"


def write_walkthrough(grid_results, path, return_rows=None, tax_rows=None):
    incomes = sorted(int(k) for k in grid_results)
    example_income = incomes[len(incomes) // 2]
    example = grid_results[str(example_income)]
    median = example["median_path"]
    s = example["summary"]

    L = []
    L.append("# Does SRS make you richer? — a plain-language walkthrough\n\n")
    L.append(
        "Generated by `srs_simulation.py`. It plays out many possible futures for the same "
        "person — the market rising and falling each year, and the tax rules possibly drifting "
        "— then reports the middle outcome and the range. It is **not** advice or a forecast; "
        "it stress-tests the model in `srs_model.py`. SRS is Singapore's optional retirement "
        "account: you get a tax discount for paying in, and pay tax on only half of what you "
        "take out later.\n\n"
    )

    # --- the bottom line
    adv = s["advantage"]
    verdict = "worth it ✅" if adv["median"] > 0 else "not worth it ❌"
    L.append("## The bottom line\n\n")
    L.append(
        f"For someone with **{_money(example_income)}** taxable income, using SRS leaves them "
        f"about **{_friendly(adv['median'])} richer** by the end than if they had simply "
        f"invested the same out-of-pocket money in a normal account — so it is **{verdict}**\n\n"
        f"Depending on how markets and taxes turn out, that head start lands somewhere between "
        f"**{_friendly(adv['p10'])}** (unlucky) and **{_friendly(adv['p90'])}** (lucky), across "
        f"{s['n_paths']} simulated lifetimes. Both paths start from the exact same amount of "
        f"your own cash — the tax discount is the extra money SRS lets you invest.\n\n"
    )

    # --- head to head
    ws = s["wealth_with_srs"]
    wo = s["wealth_without_srs"]
    L.append("## 1. With SRS vs. without\n\n")
    L.append(
        f"| | Money at the end (middle outcome) | Unlucky → lucky |\n|---|---|---|\n"
        f"| **With SRS** | {_friendly(ws['median'])} | {_friendly(ws['p10'])} → {_friendly(ws['p90'])} |\n"
        f"| **Without SRS** (invest normally) | {_friendly(wo['median'])} | {_friendly(wo['p10'])} → {_friendly(wo['p90'])} |\n\n"
    )

    # --- keep adding?
    first = median["yearly_contributions"][0]
    save_now = first["relief_rate"]
    pay_later = first["breakeven_tc"]  # = 0.5 * marginal exit rate
    L.append("## 2. Should you keep putting money in?\n\n")
    L.append(
        f"Two ways to look at the **next dollar** you put in, in the first year:\n\n"
        f"- **Right now (the marginal view):** you save about **{save_now*100:.0f}¢** of tax on "
        f"that dollar today.\n"
        f"- **Later:** you'll pay about **{pay_later*100:.1f}¢** of tax when you take it out.\n"
        f"- Since {save_now*100:.0f}¢ saved beats {pay_later*100:.1f}¢ paid, the next dollar is "
        f"**worth putting in**.\n\n"
        f"Adding more only stops being worth it once your SRS pot would grow past roughly "
        f"**$1.85M** (where the tax you'd pay taking it out finally catches up with the discount "
        f"going in). The middle simulated pot here reaches "
        f"**{_friendly(s['srs_at_retirement']['median'])}** — well under that line.\n\n"
    )
    flip_frac = s["fraction_of_paths_where_contributing_ever_stops_paying"]
    L.append(
        f"Across all simulated lifetimes at this income, a tax shock made a dollar not-worth-it "
        f"at some point in **{_pct(flip_frac)}** of them.\n\n"
    )

    # --- taking it out
    gap = s["smart_vs_rule40_tax_gap"]
    L.append("## 3. Taking the money out: the smart way pays less tax\n\n")
    L.append(
        f"The model takes the money out with a **smart plan** that re-decides each year how much "
        f"to withdraw, based on how your investments actually did (this is the \"MPC\" strategy). "
        f"Compared with the popular **\"take $40,000 a year\"** rule of thumb, the smart plan "
        f"pays about **{_friendly(gap['median'])} less tax** in the middle outcome "
        f"(range {_friendly(gap['p10'])} → {_friendly(gap['p90'])}). The gap is small when tax "
        f"brackets sit still and grows when a tax shock lands mid-withdrawal.\n\n"
    )

    # --- after the window
    aw = median["after_window"]
    L.append("## 4. After the money is out: spend it, or leave it?\n\n")
    L.append(
        f"With the **{_friendly(median['wealth_with_srs'])}** you end up holding, two honest "
        f"choices:\n\n"
        f"- **Spend it evenly** so it runs out at the assumed age of death: about "
        f"**{_friendly(aw['spend_to_zero_annual'])} a year** to spend, nothing left for family.\n"
        f"- **Never touch it** and leave it to family: about **{_friendly(aw['bequest_if_untouched'])}** "
        f"left behind.\n\n"
    )

    # --- break out early
    mid = median["yearly_contributions"][len(median["yearly_contributions"]) // 2]
    hurdle = mid["early_exit_breakeven_return"]
    L.append("## 5. Breaking out early: how good must an outside deal be?\n\n")
    if hurdle is not None:
        L.append(
            f"Say a great opportunity comes along partway through (year {mid['year']}) and you're "
            f"tempted to pull your money out early, paying the 5% penalty and full tax. To come "
            f"out ahead, that outside opportunity would have to earn more than "
            f"**{_pct(hurdle)} every year** until you'd have been allowed to withdraw anyway. "
            f"For scale: a fixed deposit pays ~3% and the stock market averages ~7%, so this "
            f"only makes sense for a genuinely exceptional deal. The hurdle climbs the closer "
            f"you are to being allowed to withdraw.\n\n"
        )

    # --- grid
    L.append("## 6. Every income level, side by side\n\n")
    L.append(
        "The SRS pot itself is the same at every income (everyone pays in the same capped "
        "amount). What changes with income is the **tax discount** you get and therefore the "
        "**head start** SRS gives you.\n\n"
    )
    L.append(
        "| Taxable income | Head start with SRS (middle) | Unlucky → lucky | Tax discount earned |\n"
        "|---|---|---|---|\n"
    )
    for income in incomes:
        gs = grid_results[str(income)]["summary"]
        a = gs["advantage"]
        L.append(
            f"| {_money(income)} | {_friendly(a['median'])} | "
            f"{_friendly(a['p10'])} → {_friendly(a['p90'])} | "
            f"{_friendly(gs['total_relief_received']['median'])} |\n"
        )

    if return_rows:
        L.append("\n## 7. How the market changes the answer\n\n")
        L.append("The dollar head start grows with the market, but the *percentage* edge shrinks "
                 "(the tax-free half covers less of a bigger pot).\n\n")
        L.append("| Average market return | Head start with SRS (middle) | As a % |\n|---|---|---|\n")
        for r in return_rows:
            L.append(f"| {r['mean_return']*100:.0f}% a year | {_friendly(r['advantage']['median'])} | "
                     f"{_pct(r['advantage_pct']['median'])} |\n")

    if tax_rows:
        L.append("\n## 8. How the tax future changes the answer\n\n")
        L.append("Three futures for the tax bands across the contributing years. Bracket creep "
                 "actually *raises* the advantage — a rising salary drifts into higher bands, so a "
                 "bigger discount goes in.\n\n")
        L.append("| Tax future | Head start with SRS (middle) | Unlucky → lucky |\n|---|---|---|\n")
        for r in tax_rows:
            a = r["advantage"]
            L.append(f"| {r['regime']} | {_friendly(a['median'])} | "
                     f"{_friendly(a['p10'])} → {_friendly(a['p90'])} |\n")

    L.append(
        "\n## What this does *not* model\n\n"
        "Mortality risk (age at death is a fixed input, not a probability), the annuity clause, "
        "the foreigner withholding concession, other retirement income, and the $80,000 overall "
        "personal-relief cap. The tax-drift model is illustrative, not a calibrated forecast. "
        "See `docs/open-tasks.md` and the docstrings in `srs_simulation.py`.\n"
    )

    with open(path, "w") as f:
        f.write("".join(L))
